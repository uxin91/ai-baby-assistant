export function getAIResponse(question: string): string {
  const lowerQuestion = question.toLowerCase();

  for (const entry of knowledge) {
    if (entry.keywords.some((keyword) => lowerQuestion.includes(keyword))) {
      return entry.answer;
    }
  }

  if (lowerQuestion.includes('你好') || lowerQuestion.includes('嗨') || lowerQuestion.includes('hi')) {
    return (
      '你好！我是你的AI育儿助手\n\n' +
      '我可以帮你解答以下方面的问题：\n' +
      '· 宝宝发烧、湿疹等常见症状\n' +
      '· 母乳喂养和辅食添加\n' +
      '· 睡眠问题\n' +
      '· 疫苗接种\n' +
      '· 生长发育\n' +
      '· 出牙护理\n\n' +
      '请问有什么需要帮助的？'
    );
  }

  return (
    `感谢你的提问！关于"${question}"，我建议：\n\n` +
    '1. 咨询儿科医生 - 专业问题请咨询医生获取个性化建议\n' +
    '2. 参考权威资料 - 可查阅《中国居民膳食指南》婴幼儿部分\n' +
    '3. 继续向我提问 - 你可以尝试用更具体的关键词提问\n\n' +
    '我擅长回答的话题：发烧、辅食、睡眠、母乳喂养、湿疹、便秘、疫苗、生长发育、出牙、吐奶等。\n\n' +
    '试试这样提问："宝宝发烧怎么办？"或"什么时候开始加辅食？"'
  );
}
